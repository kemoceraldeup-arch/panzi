// src/data/localRecipes.ts
//
// The fixed list behind three of the four category tabs on the Recipes
// screen — Quick and Easy, Snacks, Main Dish, and All (which is just this
// whole list, unfiltered). None of these read from the pantry or call the
// model: they are a cookbook, not a suggestion engine. That distinction is
// the point — "what could I cook, generally" and "what should I cook from
// what I actually have" are different questions, and only the second one
// needs an AI call. See RecipesScreen's pantryOnly branch for where that
// call still happens.
//
// One entry per dish this app already has a real photo for (see
// assets/dishes/ and theme/dishPhotos.ts's DISH_KEYS) — 51 of the 52 keys
// there carry a photo; the 52nd, 'lugaw', doesn't yet and is left out of
// this list for the same reason the photo map leaves it commented out.
// `dishKey` is what dishPhoto() looks up, so every recipe here renders its
// real photo, never the gradient tile.
//
// `category` is deliberately a single value, not an array: a dish either
// leads the Quick and Easy tab or it doesn't, and letting one recipe answer
// to two tabs would mean the count on each tab no longer describes what's
// actually behind it. A dish that could plausibly go either way (a fast
// version of an otherwise slow-cooked ulam) is filed under the category a
// home cook would actually go looking for it in, not the one that makes it
// available in the most places.

